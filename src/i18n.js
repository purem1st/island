function savedUiLanguage() {
  try { return JSON.parse(localStorage.getItem('language')) === 'en' ? 'en' : 'ru'; }
  catch { return 'ru'; }
}
let uiLanguage = savedUiLanguage();
function uiText(text) {
  return uiLanguage === 'en' ? ENGLISH[text] ?? text : text;
}
function uiLocale() {
  return uiLanguage === 'en' ? 'en-GB' : 'ru-RU';
}

// Only markup owned by the interface is registered here, before user data is rendered.
const staticTranslations = [];
function registerTranslations(root) {
  const visit = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const source = node.textContent.trim();
      if (Object.hasOwn(ENGLISH, source)) {
        const render = () => { node.textContent = uiText(source); };
        staticTranslations.push(render);
        render();
      }
    } else if (node.nodeType === Node.ELEMENT_NODE && !['SCRIPT', 'STYLE'].includes(node.tagName) && !node.hasAttribute('data-language')) {
      for (const attr of ['title', 'placeholder', 'aria-label']) {
        const source = node.getAttribute(attr);
        if (source && Object.hasOwn(ENGLISH, source)) {
          const render = () => node.setAttribute(attr, uiText(source));
          staticTranslations.push(render);
          render();
        }
      }
      Array.from(node.childNodes).forEach(visit);
    }
  };
  visit(root);
}
document.documentElement.lang = uiLanguage;
registerTranslations(document.body);
